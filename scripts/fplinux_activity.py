"""Generate the shared activity indicator's alpha masks from UI profiles."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import fplinux_ui_profile

PHASES = 8
SAMPLES = 4


def octant(x: int, y: int) -> int:
    """Clockwise octants from twelve, with diagonal samples in the next octant."""
    if y < 0:
        if x >= 0:
            return 0 if x < -y else 1
        return 7 if -x <= -y else 6
    if x >= 0:
        return 2 if x > y else 3
    return 5 if -x >= y else 4


def mask(size: int, width: int, phase: int | None) -> bytes:
    """Rasterize one quarter ring, averaging a fixed grid of subpixel samples."""
    if size < 4 or not 0 < width < size // 2:
        message = "activity size and width do not describe a ring"
        raise ValueError(message)
    outer = (size * SAMPLES) ** 2
    inner = ((size - 2 * width) * SAMPLES) ** 2
    pixels = bytearray()
    for y in range(size):
        for x in range(size):
            covered = 0
            for row in range(SAMPLES):
                dy = 2 * (y * SAMPLES + row) + 1 - size * SAMPLES
                for column in range(SAMPLES):
                    dx = 2 * (x * SAMPLES + column) + 1 - size * SAMPLES
                    radius = dx * dx + dy * dy
                    if inner <= radius <= outer and (
                        phase is None or (octant(dx, dy) - phase) % PHASES < 2
                    ):
                        covered += 1
            pixels.append((255 * covered + SAMPLES * SAMPLES // 2) // (SAMPLES * SAMPLES))
    return bytes(pixels)


def pixel_array(symbol: str, pixels: bytes) -> list[str]:
    """Write a shared alpha plane as a C constant array."""
    return [
        f"static const uint8_t {symbol}[] = {{",
        *(
            "\t" + ", ".join(f"0x{pixel:02x}" for pixel in pixels[start : start + 16]) + ","
            for start in range(0, len(pixels), 16)
        ),
        "};",
        "",
    ]


def image_descriptor(symbol: str, size: int) -> list[str]:
    """Give an immutable mask an immutable LVGL source identity."""
    return [
        f"static const lv_image_dsc_t {symbol}_image = {{",
        "\t.header = {",
        "\t\t.magic = LV_IMAGE_HEADER_MAGIC,",
        "\t\t.cf = LV_COLOR_FORMAT_A8,",
        f"\t\t.w = {size}, .h = {size}, .stride = {size},",
        "\t},",
        f"\t.data_size = {size * size},",
        f"\t.data = {symbol},",
        "};",
        "",
    ]


def render(data: dict[str, Any], *, lvgl: bool = False) -> str:
    """Return the shared activity phases for the supported UI screen profiles."""
    fplinux_ui_profile.render(data)
    pairs = sorted(
        {
            (data["profiles"][name]["spinner_size"], data["profiles"][name]["spinner_width"])
            for name in fplinux_ui_profile.PROFILES
        }
    )
    phases = range(PHASES)
    lines = [
        # The generated header's licence tag, not this Python string's.
        # REUSE-IgnoreStart
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        # REUSE-IgnoreEnd
        "/* Generated by scripts/fplinux_activity.py; do not edit. */",
        "",
    ]
    records = []
    for size, width in pairs:
        track = f"activity_{size}_{width}_track"
        lines.extend(pixel_array(track, mask(size, width, None)))
        if lvgl:
            lines.extend(image_descriptor(track, size))
        for phase in phases:
            symbol = f"activity_{size}_{width}_{phase}"
            lines.extend(pixel_array(symbol, mask(size, width, phase)))
            if lvgl:
                lines.extend(image_descriptor(symbol, size))
                records.append(
                    f"\t{{ {size}, {width}, {phase}, &{symbol}_image, &{track}_image }},"
                )
            else:
                records.append(f"\t{{ {width}, {phase}, {{ {size}, {symbol}, {track} }} }},")
    if lvgl:
        lines.extend(
            (
                "struct fplinux_ui_activity_entry {",
                "\tunsigned int size, width, phase;",
                "\tconst lv_image_dsc_t *image, *track;",
                "};",
                "static const struct fplinux_ui_activity_entry ui_activity_images[] = {",
            )
        )
    else:
        lines.append("static const struct fplinux_activity_entry activity_masks[] = {")
    lines.extend(records)
    lines.extend(("};", ""))
    return "\n".join(lines)


def main() -> int:
    """Generate one explicit output from the declared profile input."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tokens", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--lvgl", action="store_true", help="emit immutable LVGL image sources")
    args = parser.parse_args()
    try:
        result = render(json.loads(args.tokens.read_text()), lvgl=args.lvgl)
        args.output.write_text(result, encoding="utf-8")
    except (OSError, ValueError) as error:
        parser.exit(1, f"activity: {error}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
