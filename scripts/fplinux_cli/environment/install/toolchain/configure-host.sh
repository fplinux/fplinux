#!/bin/sh
set -eu

llvm_source=${1:?LLVM 23.1.6 source directory}
llvm_build=${2:?Empty build directory}
ninja_path=${3:?Absolute path to Ninja}
host=x86_64-alpine-linux-musl

cmake -S "$llvm_source/llvm" -B "$llvm_build" -G Ninja \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ \
	-DCMAKE_MAKE_PROGRAM="$ninja_path" \
	-DCMAKE_C_FLAGS_RELEASE='-O2 -DNDEBUG' \
	-DCMAKE_CXX_FLAGS_RELEASE='-O2 -DNDEBUG' \
	-DCMAKE_DISABLE_PRECOMPILE_HEADERS=ON \
	-DCMAKE_EXE_LINKER_FLAGS='-fuse-ld=lld -Wl,--threads=1' \
	-DCMAKE_SHARED_LINKER_FLAGS='-fuse-ld=lld -Wl,--threads=1' \
	-DPython3_EXECUTABLE=/usr/bin/python3.14 \
	-DCMAKE_INSTALL_PREFIX=/usr/lib/llvm23 \
	-DCMAKE_INSTALL_RPATH=/usr/lib/llvm23/lib \
	-DLLVM_HOST_TRIPLE="$host" -DLLVM_DEFAULT_TARGET_TRIPLE="$host" \
	-DLLVM_ENABLE_PROJECTS='clang;lld' \
	-DLLVM_TARGETS_TO_BUILD='X86;ARM;AArch64' \
	-DLLVM_ENABLE_LLD=ON -DLLVM_ENABLE_LTO=OFF \
	-DLLVM_PARALLEL_COMPILE_JOBS=2 -DLLVM_PARALLEL_LINK_JOBS=1 \
	-DLLVM_PARALLEL_TABLEGEN_JOBS=1 \
	-DLLVM_BUILD_LLVM_DYLIB=ON -DLLVM_LINK_LLVM_DYLIB=ON \
	-DLLVM_ENABLE_RTTI=ON -DLLVM_ENABLE_EH=ON \
	-DLLVM_ENABLE_FFI=FORCE_ON -DLLVM_ENABLE_CURL=FORCE_ON \
	-DLLVM_ENABLE_LIBXML2=FORCE_ON -DLLVM_ENABLE_LIBEDIT=OFF \
	-DLLVM_ENABLE_ZLIB=FORCE_ON -DLLVM_ENABLE_ZSTD=FORCE_ON \
	-DLLVM_ENABLE_BINDINGS=OFF -DLLVM_APPEND_VC_REV=OFF \
	-DLLVM_USE_RELATIVE_PATHS_IN_FILES=ON \
	-DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_BENCHMARKS=OFF \
	-DLLVM_INCLUDE_EXAMPLES=OFF -DLLVM_INCLUDE_DOCS=OFF \
	-DCLANG_INCLUDE_TESTS=OFF -DCLANG_ENABLE_STATIC_ANALYZER=ON \
	-DCLANG_LINK_CLANG_DYLIB=ON \
	-DCLANG_PYTHON_BINDINGS_VERSIONS=3.14 \
	-DCLANG_DEFAULT_PIE_ON_LINUX=ON -DCLANG_CONFIG_FILE_SYSTEM_DIR=/etc/clang23
