/* The static property tables generated by the Configurator. */
extern char *midp_systemKey[];

/* Callouts of the generated table (midp_property_callouts.h). */
char *getLocalTimeZone(void);
char *getLocalHostName(void);

/* From midpEvents.c (events/eventqueue/reference). */
int InitializeEvents(void);
void FinalizeEvents(void);
void midp_resetEvents(void);

#define LOCALE_PROP "microedition.locale"
#define TIMEZONE_PROP "com.sun.cldc.util.j2me.TimeZoneImpl.timezone"
#define HOSTNAME_PROP "microedition.hostname"

/* Path that can never be created, used when the caller gives no storage. */
#define NO_STORAGE_DIR "/dev/null/fplinux-phoneme-no-storage"

static int initialized;
static int storage_done, config_done, events_done, ui_done;

static void fail(const char *what)
{
	fprintf(stderr, "fplinux-phoneme: MIDP init: %s failed\n", what);
}

/*
 * "ru_RU.UTF-8@x" -> "ru-RU"; NULL for C/POSIX/empty or a malformed value.
 * MIDP locales are "ll" or "ll-CC" (MIDP 2.0 spec, microedition.locale).
 */
static const char *locale_from_env(char *buf, size_t size)
{
	static const char *const vars[] = { "LC_ALL", "LC_MESSAGES", "LANG" };
	size_t i;

	for (i = 0; i < sizeof(vars) / sizeof(vars[0]); i++) {
		const char *v = getenv(vars[i]);
		size_t n = 0;

		if (v == NULL || *v == '\0')
			continue;
		if (strcmp(v, "C") == 0 || strcmp(v, "POSIX") == 0 ||
		    strncmp(v, "C.", 2) == 0)
			return NULL;
		while (n < 2 && islower((unsigned char)v[n]))
			n++;
		if (n != 2 || size < 6)
			return NULL;
		buf[0] = v[0];
		buf[1] = v[1];
		buf[2] = '\0';
		if (v[2] == '_' && isupper((unsigned char)v[3]) &&
		    isupper((unsigned char)v[4]) &&
		    (v[5] == '\0' || v[5] == '.' || v[5] == '@')) {
			buf[2] = '-';
			buf[3] = v[3];
			buf[4] = v[4];
			buf[5] = '\0';
		} else if (v[2] != '\0' && v[2] != '.' && v[2] != '@') {
			return NULL;
		}
		return buf;
	}
	return NULL;
}

/*
 * Copy the MIDP system-scope properties into the VM, so System.getProperty()
 * sees them (the CLDC jvmspi keeps its own list). Keys may appear twice in
 * the generated table (project overrides); getSystemProperty() returns the
 * effective value.
 */
static void export_system_properties(void)
{
	char locale[8];
	const char *loc;
	char *v;
	int i, j;

	for (i = 0; midp_systemKey[i] != NULL; i++) {
		const char *key = midp_systemKey[i];
		const char *value;

		for (j = 0; j < i; j++) {
			if (strcmp(midp_systemKey[j], key) == 0)
				break;
		}
		if (j < i)
			continue; /* already exported */
		value = getSystemProperty(key);
		if (value != NULL)
			JVMSPI_SetSystemProperty(key, value);
	}

	loc = locale_from_env(locale, sizeof(locale));
	if (loc != NULL) {
		setSystemProperty(LOCALE_PROP, loc);
		JVMSPI_SetSystemProperty(LOCALE_PROP, loc);
	}
	v = getLocalTimeZone();
	if (v != NULL)
		JVMSPI_SetSystemProperty(TIMEZONE_PROP, v);
	v = getLocalHostName();
	if (v != NULL)
		JVMSPI_SetSystemProperty(HOSTNAME_PROP, v);
}

bool fplinux_pm_midp_init(const char *storage_dir)
{
	if (initialized)
		return true;

	if (storageInitialize((char *)FPLINUX_PM_MIDP_HOME,
			      (char *)(storage_dir != NULL ? storage_dir :
							     NO_STORAGE_DIR)) !=
	    0) {
		fail("storage");
		goto error;
	}
	storage_done = 1;
	if (initializeConfig() != 0) {
		fail("properties");
		goto error;
	}
	config_done = 1;
	export_system_properties();
	if (InitializeEvents() != 0) {
		fail("event queue");
		goto error;
	}
	events_done = 1;
	if (lcdlf_ui_init() != 0) {
		fail("screen");
		goto error;
	}
	ui_done = 1;
	midp_resetEvents();
	initialized = 1;
	return true;

error:
	fplinux_pm_midp_cleanup();
	return false;
}

void fplinux_pm_midp_cleanup(void)
{
	if (ui_done) {
		lcdlf_ui_finalize();
		ui_done = 0;
	}
	if (events_done) {
		FinalizeEvents();
		events_done = 0;
	}
	if (config_done) {
		finalizeConfig();
		config_done = 0;
	}
	if (storage_done) {
		storageFinalize();
		storage_done = 0;
	}
	initialized = 0;
}

/*
 * Upstream modules call midpInit(LIST_LEVEL) before touching storage (e.g.
 * rms.c when it removes a suite's stores). fplinux_pm_midp_init() has done
 * that work already.
 */
int midpInit(int level)
{
	(void)level;
	return initialized ? 0 : -1;
}

