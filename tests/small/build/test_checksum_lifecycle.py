from tests import ROOT

APORT_FILES = ROOT / "tests/fixtures/checksum-aport"

if TYPE_CHECKING:
    from collections.abc import Callable


PACKAGE = "synthetic-checksum-aport"


class ChecksumAportContext:
    """Own the canonical recipe and its controlled container boundary."""

    def __init__(self, root: Path) -> None:
        """Create one canonical aport with an ordinary local source."""
        self.root = root
        self.aport = self.root / "alpine/aports" / PACKAGE
        self.aport.mkdir(parents=True)
        self.apkbuild = self.aport / "APKBUILD"
        self.apkbuild.write_bytes((APORT_FILES / "before.APKBUILD").read_bytes())
        self.apkbuild.chmod(0o640)
        (self.aport / "local.c").write_bytes(b"int local_source;\n")
        shutil.copytree(
            ROOT / "scripts/fplinux_cli/alpine/checksum",
            self.root / "scripts/fplinux_cli/alpine/checksum",
        )

    def run(self, container_run: Callable[..., None]) -> None:
        """Invoke the checksum workflow with a controlled image and OCI execution."""
        with (
            mock.patch.object(common, "ROOT", self.root),
            mock.patch.object(image_store, "ROOT", self.root),
            mock.patch.object(workspace_inputs, "ROOT", self.root),
            mock.patch.object(workspace_staging, "ROOT", self.root),
            mock.patch.object(output, "ROOT", self.root),
            mock.patch.object(
                images,
                "load_container_lock",
                return_value={"oci": {"repository": "localhost/fplinux-build"}},
            ),
            mock.patch.object(images, "container_image_recipe_digest", return_value="e" * 64),
            mock.patch.object(kern_env, "kern_available", return_value=True),
            mock.patch.object(kern_env, "require_kern", return_value="/usr/bin/kern"),
            mock.patch.object(
                image_store,
                "current_image_state",
                return_value=ImageState("e" * 64, "a" * 64, "a" * 64),
            ),
            mock.patch.object(kern_env, "kern_environment", return_value={}),
            mock.patch.object(output.Stage, "run", autospec=True, side_effect=container_run),
            contextlib.redirect_stdout(io.StringIO()),
            contextlib.redirect_stderr(io.StringIO()),
        ):
            output.run_entrypoint(lambda: checksum_commands.checksum_aport(PACKAGE, offline=True))

    @staticmethod
    def staged_apkbuild(command: list[str]) -> Path:
        """Resolve the private aport through the OCI workspace mount boundary."""
        workspace_sources: list[Path] = []
        for index, argument in enumerate(command[:-1]):
            if argument != "--volume":
                continue
            mount = command[index + 1].split(":")
            if len(mount) >= 2 and mount[1] == "/workspace":
                workspace_sources.append(Path(mount[0]))
        assert (len(workspace_sources)) == (1)

        workdir_index = command.index("--workdir")
        container_workdir = Path(command[workdir_index + 1])
        relative_workdir = container_workdir.relative_to("/workspace")
        return workspace_sources[0] / relative_workdir / "APKBUILD"


@pytest.fixture
def checksum_aport(tmp_path: Path) -> ChecksumAportContext:
    """Supply one isolated canonical aport for the checksum scenario."""
    return ChecksumAportContext(tmp_path)


class ChecksumAportTests:
    """Publish only validated checksum-block changes from an isolated OCI stage."""

    def test_success_replaces_only_the_checksum_block_atomically(
        self, checksum_aport: ChecksumAportContext
    ) -> None:
        """Publish complete generated bytes while preserving recipe text and mode."""
        inode_before = checksum_aport.apkbuild.stat().st_ino

        def generate(_stage: output.Stage, command: list[str], **_kwargs: object) -> None:
            generated = checksum_aport.staged_apkbuild(command)
            generated.write_bytes((APORT_FILES / "after.APKBUILD").read_bytes())

        checksum_aport.run(generate)

        assert (checksum_aport.apkbuild.read_bytes()) == (
            (APORT_FILES / "after.APKBUILD").read_bytes()
        )
        assert (checksum_aport.apkbuild.stat().st_mode & 0o777) == (0o640)
        assert (checksum_aport.apkbuild.stat().st_ino) != (inode_before)
        assert (list(checksum_aport.aport.glob(".APKBUILD.*"))) == ([])

    def test_container_shares_downloads_and_keeps_the_stage_private(
        self, checksum_aport: ChecksumAportContext
    ) -> None:
        """Keep the persistent source cache shared without exposing the private stage."""

        def inspect(_stage: output.Stage, command: list[str], **_kwargs: object) -> None:
            mounts = {}
            for index, argument in enumerate(command[:-1]):
                if argument != "--volume":
                    continue
                parts = command[index + 1].split(":")
                destination = parts[1]
                mounts[destination] = "ro" if parts[2:] == ["ro"] else "rw"
            assert (mounts) == (
                {
                    "/cache/downloads": "rw",
                    "/workspace": "rw",
                }
            )
            generated = checksum_aport.staged_apkbuild(command)
            generated.write_bytes((APORT_FILES / "after.APKBUILD").read_bytes())

        checksum_aport.run(inspect)

    def test_non_checksum_generation_failure_keeps_canonical_apkbuild(
        self, checksum_aport: ChecksumAportContext
    ) -> None:
        """Reject OCI output that changes recipe text before atomic publication."""
        inode_before = checksum_aport.apkbuild.stat().st_ino

        def generate_invalid(_stage: output.Stage, command: list[str], **_kwargs: object) -> None:
            generated = checksum_aport.staged_apkbuild(command)
            generated.write_bytes(
                (APORT_FILES / "after.APKBUILD").read_bytes().replace(b"pkgver=1\n", b"pkgver=2\n")
            )

        with pytest.raises(SystemExit):
            checksum_aport.run(generate_invalid)

        assert (checksum_aport.apkbuild.read_bytes()) == (
            (APORT_FILES / "before.APKBUILD").read_bytes()
        )
        assert (checksum_aport.apkbuild.stat().st_mode & 0o777) == (0o640)
        assert (checksum_aport.apkbuild.stat().st_ino) == (inode_before)
        assert (list(checksum_aport.aport.glob(".APKBUILD.*"))) == ([])
